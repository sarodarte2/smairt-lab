@dataclass(frozen=True)
class Finding:
    """One violation of the state contract. ``severity`` is ``error`` or ``warning``."""

    id: str
    severity: str
    path: str
    message: str


@dataclass(frozen=True)
class Suggestion:
    """One growth-channel note. Advisory only: never affects the exit code."""

    id: str
    path: str
    message: str


@dataclass(frozen=True)
class CheckReport:
    """The full result of :func:`run_checks`."""

    findings: tuple[Finding, ...]
    suggestions: tuple[Suggestion, ...]

    @property
    def exit_code(self) -> int:
        """1 if there are any errors/warnings, else 0 — what the CLI process exits with.

        Suggestions never affect this: they're advisory-only, so a project
        with suggestions but zero findings still exits 0 (success).
        """
        return 1 if self.findings else 0


@dataclass(frozen=True)
class StatusDocument:
    """The parsed contents of STATUS.md — the project's one hand-maintained ledger
    (Part I, foundation 3). This is the single reader for STATUS.md: :func:`run_checks`
    consults only ``updated`` (rule 5, STATUS drift); ``smairt status`` (WP3) reads the
    rest to print Focus/Next/Open questions. Keeping both behind :func:`read_status`
    means there is exactly one place that parses this file.
    """

    updated: date | None
    focus: str
    next_step: str
    open_questions: tuple[str, ...]
    decisions: tuple[str, ...]


def read_status(project_root: Path) -> StatusDocument | None:
    """Read and parse ``STATUS.md``, or ``None`` if it is absent or malformed."""
    status_path = project_root / "STATUS.md"
    if not status_path.is_file():
        return None
    try:
        fields, body = frontmatter.read(status_path)
    except frontmatter.FrontmatterError:
        return None
    sections = _split_status_sections(body)
    return StatusDocument(
        updated=_coerce_date(fields.get("updated")),
        focus=sections.get("focus", ""),
        next_step=sections.get("next", ""),
        open_questions=_status_bullets(sections.get("open questions", "")),
        decisions=_status_bullets(sections.get("decisions", "")),
    )


def _split_status_sections(body: str) -> dict[str, str]:
    """Split a Markdown body into ``## Heading`` sections, keyed by lowercase heading.

    Despite the name, this has nothing STATUS.md-specific in it — it is a
    plain ``## Heading`` splitter, so rule SMAIRT010 reuses it directly
    against a question unit's own README body to find its ``## Analysis
    plan`` section, rather than writing a second parser for the same shape.
    Structural only (foundation 5): this never inspects or judges the
    researcher's prose, only where one heading ends and the next begins.
    """
    sections: dict[str, str] = {}
    heading: str | None = None
    content: list[str] = []
    for line in body.splitlines():
        if line.startswith("## "):
            if heading is not None:
                sections[heading] = "\n".join(content).strip()
            heading = line[3:].strip().lower()
            content = []
        elif heading is not None:
            content.append(line)
    if heading is not None:
        sections[heading] = "\n".join(content).strip()
    return sections


def _status_bullets(text: str) -> tuple[str, ...]:
    """Pull the ``- item`` bullet lines out of one STATUS.md section's text.

    Used for the "Open questions" and "Decisions" sections, which are
    written as a Markdown bullet list. Non-bullet lines are dropped rather
    than raising, since this is reading free-text prose (foundation 5: never
    judge the researcher's prose) — a section that isn't a tidy bullet list
    just yields fewer (or zero) items instead of erroring.
    """
    items = []
    for line in text.splitlines():
        stripped = line.strip()
        if stripped.startswith("-"):
            stripped = stripped[1:].strip()
        if stripped:
            items.append(stripped)
    return tuple(items)


@dataclass(frozen=True)
class _Unit:
    """A parsed (or unparseable) unit folder under experiments/, for internal reuse.

    ``body`` (the README's free-text half, below the frontmatter block) is
    carried here too, not just ``fields`` — rule SMAIRT010 needs it to check
    the ``## Analysis plan`` section, and reading it once here means that
    rule doesn't re-read every README a second time on its own.
    """

    path: Path
    rel: str
    error: str | None
    fields: dict[str, Any]
    body: str
    kind: UnitKind | None
    status: str | None


def run_checks(project_root: Path) -> CheckReport:
    """Run every WP2 rule against the project at ``project_root``. Read-only.

    This is the one function that ties every rule together (thirteen finding
    rules, SMAIRT001-013, plus five advisory suggestions, SMAIRT101-105): it
    loads every unit once (:func:`_load_units`), then hands that same list to
    each rule function in turn, collecting their findings/suggestions into
    one report. To add a new rule, write a ``_check_*`` (findings) or
    ``_suggest_*`` (suggestions) function following the pattern below and
    call it from here — see docs/ARCHITECTURE.md.
    """
    units = _load_units(project_root)

    findings: list[Finding] = []
    findings += _check_project_config(project_root)
    findings += _check_frontmatter_schema(units)
    findings += _check_evidence_pointers(project_root, units)
    findings += _check_receipt_completeness(units)

    suggestions: list[Suggestion] = []
    if project_module.is_git_work_tree(project_root):
        findings += _check_log_immutability(project_root, units)
    elif not _git_opt_out_recorded(project_root):
        # No Git, no history to check for edits after the fact -- rule
        # SMAIRT004 simply can't run, so we say so once (SMAIRT101) instead
        # of silently skipping it. Unless the researcher already told
        # `smairt new` they were choosing no Git on purpose (DG-5, see
        # :func:`_git_opt_out_recorded`) -- SMAIRT101 exists to catch an
        # ACCIDENT (a project nobody ever `git init`'d), and a recorded
        # choice is not one.
        suggestions.append(
            Suggestion(
                SUGGEST_GIT_UNAVAILABLE,
                ".",
                "not a Git repository: raw-log immutability under logs/ cannot be verified.",
            )
        )

    findings += _check_status_drift(project_root, units)
    findings += _check_structure_drift(project_root, units)
    findings += _check_missing_readme_folders(project_root)
    findings += _check_closed_question_completeness(units)
    findings += _check_prompted_by(project_root, units)
    findings += _check_prompted_by_cycle(project_root, units)
    findings += _check_hypothesis_nonempty(units)
    findings += _check_analysis_plan_on_close(units)

    suggestions += _suggest_hpc(project_root, units)
    suggestions += _suggest_grouping(units)
    suggestions += _suggest_paper_overlay(project_root)
    suggestions += _suggest_dataset_locations(project_root)

    return CheckReport(findings=tuple(findings), suggestions=tuple(suggestions))


# --- loading -----------------------------------------------------------------


def _load_units(project_root: Path) -> list[_Unit]:
    """Read every unit folder under ``experiments/`` into a list of :class:`_Unit`.

    This is the single place every rule below gets its unit data from, so
    each rule function only has to loop over an already-parsed list instead
    of re-reading the filesystem itself. A unit whose README fails to parse
    still becomes a ``_Unit`` (with ``error`` set and ``kind``/``status`` left
    ``None``) rather than being skipped — that's what lets rule 1
    (frontmatter schema) report it as a SMAIRT001 finding.
    """
    experiments_dir = project_root / "experiments"
    if not experiments_dir.is_dir():
        return []

    units: list[_Unit] = []
    for entry in sorted(experiments_dir.iterdir(), key=lambda item: item.name):
        readme = entry / "README.md"
        if not entry.is_dir() or not readme.is_file():
            continue
        rel = str(entry.relative_to(project_root))
        try:
            fields, body = frontmatter.read(readme)
        except frontmatter.FrontmatterError as error:
            units.append(
                _Unit(
                    path=entry,
                    rel=rel,
                    error=str(error),
                    fields={},
                    body="",
                    kind=None,
                    status=None,
                )
            )
            continue

        kind: UnitKind | None
        try:
            kind = UnitKind(fields.get("kind"))
        except ValueError:
            kind = None
        status = fields.get("status")
        units.append(
            _Unit(
                path=entry,
                rel=rel,
                error=None,
                fields=fields,
                body=body,
                kind=kind,
                status=str(status) if status is not None else None,
            )
        )
    return units


