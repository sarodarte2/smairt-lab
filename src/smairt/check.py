"""``smairt check`` — the state contract (WP2).

Tier-2 enforcement (spec Part I, foundation 2): what tooling cannot generate at
creation time (tier 1), it verifies mechanically here. Derived-first (foundation
3): this module reads frontmatter, the filesystem, and Git; it never maintains a
database of its own, and it never writes anything — the one deliberate exception
elsewhere in the codebase, ``results/INDEX.md``, is regenerated by
:mod:`smairt.index`, not here.

Public entry point: :func:`run_checks`, returning a :class:`CheckReport`.

:func:`read_status` is the single reader of ``STATUS.md`` (frontmatter *and* its
``## Heading`` body sections) — reused by rule 5 below and by ``smairt status`` (WP3).

Finding IDs
-----------
Every rule below carries exactly one stable ID (the *rule* is the unit of
identity, not each way it can be violated — a rule's ``message`` text carries
the specifics). IDs are referenced by tests and, later, by WP4's hooks, so they
must not be renumbered once shipped.

Findings (severity error/warning; each instance affects the process exit code)::

    SMAIRT001  Frontmatter schema invalid: block missing/malformed, kind not
               recognized, status illegal for that kind, or a required field
               (per smairt.units) absent.                              [error]
    SMAIRT002  An evidence pointer (script:/log:/outputs:/paths:) does not
               resolve, or a CLOSED unit's script:/log: is empty.       [error]
    SMAIRT003  Receipt completeness: a unit with tool: set has an empty
               tool_version:, empty command:, or a log: that does not exist.
                                                                          [error]
    SMAIRT004  Raw-log immutability: a file under a unit's logs/ was modified
               in a later commit than the one that added it.            [error]
    SMAIRT005  STATUS drift: STATUS.md's updated: is older than a unit that
               has changed since.                                     [warning]
    SMAIRT006  Structure drift: a file loose directly under experiments/
               (outside any unit folder), or an unrecognized top-level
               project folder.                                        [warning]
    SMAIRT007  Closed-question completeness: status in {supported, refuted,
               inconclusive, dead-end} with an empty verdict:.          [error]
    SMAIRT008  A question's prompted_by: is set but does not resolve to a
               real unit (a folder with its own README.md) under
               experiments/.                                            [error]
    SMAIRT009  A question unit's hypothesis: is present but empty
               (reference units, case 3, are exempt).                   [error]
    SMAIRT010  A CLOSED question unit's '## Analysis plan' body section is
               missing or empty (reference units, case 3, are exempt).  [error]
    SMAIRT011  The project's own smairt.yaml parses but is missing, or has
               emptied out, a required identity field (name:/researcher:/
               description:).                                            [error]
    SMAIRT012  A folder directly under experiments/ has no README.md, so it
               is invisible to check/status/index.                     [warning]
    SMAIRT013  A question's prompted_by: chain loops back on itself (a
               cycle, only reachable by hand-editing frontmatter).        [error]

Advisory suggestions (a separate channel; never affect the exit code)::

    SMAIRT101  Git is unavailable, so raw-log immutability (rule SMAIRT004)
               could not be checked at all — one note, not per-file. Suppressed
               (DG-5) when smairt.yaml records the researcher's own choice not
               to use Git; still fires whenever that choice is absent or true.
    SMAIRT102  SLURM/sbatch content found in a unit but the project has no
               hpc/ folder yet.
    SMAIRT103  Three or more question units share a leading slug word: a
               grouping subfolder may be earned.
    SMAIRT104  STATUS.md mentions paper/manuscript/figure-legend work: a
               pointer to the (deferred) Paper overlay.
    SMAIRT105  A data/<x>/ subfolder exists with no README, or a README with
               no locations: entry recorded -- one note, not per-dataset.

Judgment calls a reviewer should know about
--------------------------------------------
* ``smairt unit new question`` pre-fills ``log:`` with the filename the probe
  is expected to write (``logs/<slug>.log``) before it has run. Rule SMAIRT002
  treats that as resolved for an OPEN/ACTIVE unit as long as the containing
  ``logs/`` folder exists — only a CLOSED unit is held to the exact file
  existing. This is what lets a freshly created, not-yet-run question pass
  check with zero findings (WP1's own acceptance criterion).
* Rule SMAIRT004 (log immutability) is skipped, in favor of the single
  SMAIRT101 advisory, whenever the project is not inside a Git work tree —
  this keeps `smairt check` usable before a researcher runs ``git init``.
* Rule SMAIRT005 (STATUS drift) compares calendar dates only (a file's mtime
  truncated to a date vs. STATUS.md's ``updated:`` date), not timestamps —
  matching the day-granularity the frontmatter schemas already use.
* Rule 8's growth suggestions each fire at most once per run (naming the
  first offending unit, not every one) — they are prompts to notice a
  pattern, not a per-file audit. SMAIRT105 (dataset locations) follows the
  same convention, naming the first data/<x>/ subfolder missing a recorded
  location rather than every one — a project can accumulate many datasets,
  and one nudge is enough to send a researcher to `smairt data list` to see
  the rest, rather than flooding `smairt check`'s output per dataset.
* Rule SMAIRT002's ``paths:`` field (case 3, spec Part II: reference units)
  resolves relative to the PROJECT ROOT, not the unit folder — it names
  pre-existing paths elsewhere in the tree. Every other pointer field
  (``script:``/``log:``/``outputs:``) stays unit-relative, as before.
* Rule SMAIRT002 (and rule 8's ``prompted_by:`` check, which mirrors it)
  never treats an ABSOLUTE pointer value as resolved, even when the absolute
  path genuinely exists on disk. ``pathlib`` joins an absolute right-hand
  side by discarding the left side entirely, so without this guard an
  absolute ``script:``/``log:``/``outputs:``/``paths:`` value would be
  checked against the whole filesystem instead of the project root/unit
  folder it's documented to resolve against — the one place in this module
  where "the pointer happens to exist" and "the pointer is valid" can
  silently diverge. See :func:`_pointer_resolves`.
* Rule SMAIRT006 (structure drift) also recognizes ``smairt.yaml``'s
  ``adoption.known_folders`` (written by ``smairt adopt``) as legitimate
  top-level folders, on top of the fixed scaffold set — an adopted project's
  pre-existing directories don't warn; anything new appearing after adoption
  still does.
* The one ``smairt.yaml`` degrade policy (DG-1) splits on reads versus
  writes, not on call sites. Unparseable YAML fails fast for every command at
  project-root resolution; a file that parses but is invalid is rule
  SMAIRT011. Below that, a *read* falls back silently to a documented safe
  default (:func:`smairt.connect.read_strict_hooks` -> non-strict,
  :func:`_adoption_known_folders` -> no known folders), because nothing the
  researcher asked for has gone missing. A *write* that cannot happen always
  warns (:func:`smairt.connect._record_harness`): the researcher asked for it,
  and silence would let a command report success while the change never
  landed.
* Rule SMAIRT008 (``prompted_by:`` resolves) treats a target as resolved only
  when ``experiments/<target>/README.md`` exists — the same "must actually be
  a unit, not just a folder" standard rule SMAIRT002 already holds reference
  units' ``paths:`` to. It only ever fires when ``prompted_by:`` is present;
  nothing requires the field, per spec ticket 01's answer.
* Rules SMAIRT009 (hypothesis) and SMAIRT010 (Analysis plan) both exempt
  reference units — detected the same way :func:`_check_evidence_pointers`
  distinguishes them, by ``"paths" in unit.fields`` — from firing at all. A
  reference unit describes work adopted after the fact; it was never framed
  as a testable claim, so demanding a retroactive hypothesis or plan for it
  would be absurd. Spec ticket 02 states this exemption explicitly for the
  Analysis plan rule; the hypothesis rule is new territory the ticket didn't
  directly address, but the same reasoning applies without change, so the
  same exemption is used for both.
* Rule SMAIRT009 skips a question whose ``hypothesis:`` key is absent from
  frontmatter entirely, as opposed to present-but-blank — rule SMAIRT001
  already reports a missing required field as its own finding, and firing
  both for the same defect would just be noise. This mirrors how rule
  SMAIRT002 skips a pointer field that isn't present at all (see
  :func:`_check_evidence_pointers`).
* Rule SMAIRT010 reuses :func:`_split_status_sections` against a question
  unit's own README body, not just ``STATUS.md`` — the function was already
  a generic ``## Heading`` splitter with nothing STATUS-specific in its
  implementation, so extending its one caller to two rather than writing a
  second parser was the whole point of the ticket's "reuse read_status's
  approach" instruction.
* **DG-1's degrade policy, decided once and applied everywhere:** a
  ``smairt.yaml`` that fails to PARSE (a genuine YAML syntax error) is caught
  as early as possible — :func:`smairt.project.find_project_root`, which
  every command already calls to resolve "which project am I in", raises
  :class:`smairt.project.ProjectConfigError` and every command turns that
  into a `smairt <command>: ...` failure before doing anything else. A
  ``smairt.yaml`` that PARSES but is empty, isn't a mapping, or is missing a
  required identity field is instead rule SMAIRT011 below — it can only be
  reached once the project root is already known-good, so it is a `check`
  finding like any other, not a second fail-fast path. Every OTHER reader of
  ``smairt.yaml`` in this codebase (this rule's own
  :func:`_adoption_known_folders`, and :mod:`smairt.connect`'s
  ``read_strict_hooks``/``_record_harness``) goes through the single shared
  :func:`smairt.project.read_project_config` and, on failure, silently falls
  back to its own safe default (no known folders / ``strict_hooks: False`` /
  the ``harnesses:`` list left untouched) — it does NOT print its own
  warning. This replaces the previous per-call-site inconsistency (
  ``_adoption_known_folders`` and ``read_strict_hooks`` degraded silently
  while ``_record_harness`` warned on the identical failure) with one rule:
  a broken ``smairt.yaml`` is always surfaced through exactly one of the two
  systematic channels above (fail-fast or SMAIRT011), never through an ad
  hoc per-function message that would just repeat the same news a third or
  fourth time. In the realistic case — a researcher breaks the file's YAML
  *syntax* by hand — fail-fast already stops every command, including
  ``smairt connect``, before ``read_strict_hooks`` or ``_record_harness``
  ever run, which is what actually fixes the walk's worst finding here (a
  broken file silently costing a researcher their ``strict_hooks: true``
  gate). The remaining "valid YAML, wrong shape" case is only reachable by a
  much stranger hand-edit (replacing the whole mapping with a bare list, for
  instance); it still gets caught, just the next time `smairt check` runs
  rather than instantly.
* **DG-1's required fields.** Rule SMAIRT011 requires exactly ``name:``,
  ``researcher:``, ``description:`` — the three fields
  ``_prompt_missing_identity`` (cli.py) actually asks a researcher for, and
  the only three a human being is likely to ever hand-edit. ``schema_version``/
  ``scaffold_version``/``created``/``harnesses``/``settings`` are smairt's own
  bookkeeping, already read defensively (``.get(...)`` with a fallback)
  everywhere they're consumed, and are not something a researcher edits by
  hand or would know how to "fix" if flagged — flagging them would turn this
  rule from "your project doesn't say who/what this is" into unhelpful
  pedantry about internal fields.
* **DG-1's message, one finding per broken file.** Rule SMAIRT011 emits at
  most ONE finding for a broken ``smairt.yaml`` (naming every missing/empty
  field it found, not just the first), rather than one finding per field —
  the hard requirement is that the message end by showing what a correct
  file looks like (:func:`smairt.project.example_smairt_yaml`), and pasting
  that same ~9-line block two or three times over for a file missing several
  fields would bury the useful part in repetition instead of helping.
* **DG-2 (rule SMAIRT012)** matches SMAIRT006's severity (warning, not
  error/suggestion) because it is the same class of problem — the project
  still "works", it just doesn't match the shape `smairt` can see — and the
  message points at ``smairt unit new`` as the one supported fix, the same
  as :mod:`smairt`'s ``AGENTS.md`` template already tells every researcher.
  Deliberately does not attempt to guess whether the folder is stage-shaped
  or question-shaped; that's a judgment call for the researcher, not this
  rule.
* **DG-3's SMAIRT006 sharpening**: when an unrecognized top-level folder
  itself contains a ``smairt.yaml``, :func:`_check_structure_drift` names
  that specifically ("is itself a SMAIRT project") instead of the generic
  "not part of the known scaffold" text — this is the same situation
  ``smairt new``'s own nesting warning (see :func:`smairt.project.
  find_enclosing_project`, called from ``cli.py``'s ``new`` command) already
  warns about at creation time; this is the backstop for finding it later
  (adopted from elsewhere, created before this check existed, or the warning
  was missed).
* **DG-4 (rule SMAIRT013, prompted_by cycles)**: :func:`_check_prompted_by_cycle`
  is a SEPARATE, from-scratch cycle walk over the same ``prompted_by:``
  edges rule SMAIRT008 already validates resolve — it deliberately does not
  reuse or touch :func:`smairt.index._ordered_for_index`'s own cycle guard,
  which the friction walk already verified (under a hard 15-second timeout)
  never hangs or crashes; this rule only ADDS a report of what that guard
  was silently working around. Only edges that already resolve (per
  :func:`_prompted_by_resolves`) participate — a dangling ``prompted_by:``
  is SMAIRT008's finding, not a cycle candidate, so the two rules never fire
  on the same root cause. Because each question has at most one
  ``prompted_by:`` target, the graph has out-degree <= 1 everywhere, which
  is what makes an O(n) three-color walk (unvisited/in-progress/done)
  sufficient — no recursion depth concerns, no need for a general-graph
  algorithm. A unit naming ITSELF as ``prompted_by:`` is treated as a
  degenerate, length-1 cycle, not silently ignored: it "resolves" by
  SMAIRT008's own rule (the unit's own README.md genuinely exists at that
  path), so SMAIRT008 never catches it, even though "prompted by itself" is
  exactly as impossible in real work as any longer loop. This differs from
  :func:`smairt.index._ordered_for_index`, which also refuses to nest a
  record under itself — but only to decide it shouldn't render as its own
  parent, a rendering choice this rule has no reason to copy.
* **DG-5 (SMAIRT101 suppression on a recorded git opt-out)**: a researcher who
  answers "no" to ``smairt new``'s Git prompt (or passes ``--no-git``) gets
  ``settings.git: false`` written into ``smairt.yaml``
  (:func:`smairt.project.render_identity`); :func:`_git_opt_out_recorded`
  reads it back defensively, the same shape as
  :func:`smairt.connect.read_strict_hooks`. SMAIRT101 exists to flag a
  project that has *no history to check* — usually because nobody ever ran
  ``git init``, an oversight worth a nudge. A deliberate, recorded no-git
  choice is a different fact: there will never be Git history to check,
  on purpose, so repeating the nudge every single ``smairt check`` forever
  would just be the tool arguing with a decision already made. This
  deliberately does NOT touch rule SMAIRT004 itself (log immutability):
  SMAIRT004 already only runs when :func:`smairt.project.is_git_work_tree`
  is true, so a no-Git project never reaches it either way — the opt-out
  only changes whether the ADVISORY about not being able to run it also
  fires, never a finding's severity or existence. Never promoted to a
  finding and never given its own rule id: it changes exactly one existing
  suggestion's firing condition, not the state contract itself.
"""

